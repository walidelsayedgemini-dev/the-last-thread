// Generates src/game/assetTable.ts from assets.lock.json (stable /manus-storage addresses).
// Run after every `sync-assets.mjs`:  node scripts/gen-asset-table.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const lock = JSON.parse(readFileSync('assets.lock.json', 'utf8'))
const entries = Object.entries(lock.assets)
  .filter(([key]) => key.startsWith('assets/models/') && key.endsWith('.glb'))
  .map(([key, value]) => [key.replace('assets/models/', '').replace(/\.glb$/, ''), value.path])
  .sort(([a], [b]) => a.localeCompare(b))

const body = entries.map(([id, path]) => `  '${id}': '${path}',`).join('\n')
writeFileSync(
  'src/game/assetTable.ts',
  `// GENERATED by scripts/gen-asset-table.mjs from assets.lock.json — do not edit by hand.
/** Stable storage address of every registered model, keyed by "<folder>/<name>". */
export const MODEL_URL = {
${body}
} as const

export type ModelId = keyof typeof MODEL_URL
`,
)
console.log(`asset table: ${entries.length} models`)
