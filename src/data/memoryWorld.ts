export type MemorySite = (typeof SITES)[number]
export type MemoryRegion = (typeof REGIONS)[number]
export type MemoryChapter = { id: number; region: number; phase: number; year: number; month: number; day: number; sites: MemoryPlace[]; witnesses: MemoryWitness[] }
export type MemoryPlace = { id: number; chapter: number; region: number; phase: number; slot: number; title: string; site: MemorySite }
export type MemoryWitness = { id: number; name: string; role: string; intro: string; line: string; correctSlot: number; needs: number[]; friend: boolean }

export const MEMORY_CHAPTERS: MemoryChapter[] = REGIONS.flatMap((region, area) =>
  PHASES.map((_phase, phase) => {
    const id = area * PHASES.length + phase
    const sites = SITES.slice(phase * 5, phase * 5 + 5).map((site, slot): MemoryPlace => ({
      id: id * 5 + slot, chapter: id, region: area, phase, slot, title: `${site[0]} · ${region[0]}`, site,
    }))
    const witnesses = WITNESS_ROLES[phase].map((role, seat): MemoryWitness => {
      const friend = area === phase && seat === 0 ? FRIENDS[area] : undefined
      const correctSlot = seat === 0 ? area % 2 : 2 + ((area + phase) % 3)
      return {
        id: id * 2 + seat,
        name: friend?.name ?? `${FIRST_NAMES[(area + (phase * 2 + seat) * 3) % FIRST_NAMES.length]} ${FAMILY_NAMES[phase * 2 + seat]}`,
        role, friend: Boolean(friend), correctSlot, needs: seat === 0 ? [0, 1] : [2, 3, 4],
        intro: friend?.intro ?? `${role} في ${region[3]}. حافظ أثر «${region[5]}» لأنه فارق مع ${region[4]}.`,
        line: `${friend?.line ?? `أنا ${role} بنفسي؛ ${region[5]} هو اللي خلّاني أفرّق بين النسختين.`} دليل «${sites[correctSlot].site[2]}» يطابق ${friend ? 'اللي في نسخة سنة' : 'اللي شفته سنة'} ${YEARS[phase]}.`,
      }
    })
    const mainPosition = MAIN_REGIONS[phase].findIndex(regionId => regionId === area)
    const eventOrder = mainPosition < 0 ? area + 2 : mainPosition
    return { id, region: area, phase, year: YEARS[phase], month: 3 + Math.floor(eventOrder / 6), day: 4 + (eventOrder % 6) * 4, sites, witnesses }
  }))
export const MEMORY_PLACES = MEMORY_CHAPTERS.flatMap(chapter => chapter.sites)
export const MEMORY_PEOPLE = MEMORY_CHAPTERS.flatMap(chapter => chapter.witnesses.map(witness => ({ chapter, witness })))

export function relatedChapters(chapter: MemoryChapter): MemoryChapter[] {
  const sameArea = MEMORY_CHAPTERS[chapter.region * 5 + (chapter.phase + 1) % 5]
  const corroboratingArea = MEMORY_CHAPTERS[((chapter.region + (chapter.phase + 1) * 3) % REGIONS.length) * 5 + chapter.phase]
  const partnerArea = MEMORY_CHAPTERS[((chapter.region + REGIONS.length - 1) % REGIONS.length) * 5 + chapter.phase]
  const [first, second] = MAIN_REGIONS[chapter.phase]
  const nextLead = chapter.region === first
    ? MEMORY_CHAPTERS[second * 5 + chapter.phase]
    : chapter.region === second && chapter.phase + 1 < PHASES.length
      ? MEMORY_CHAPTERS[MAIN_REGIONS[chapter.phase + 1][0] * 5 + chapter.phase + 1] : undefined
  return [...new Set([nextLead, sameArea, corroboratingArea, partnerArea].filter((c): c is MemoryChapter => Boolean(c)))]
}
