export type MemorySite = (typeof SITES_ABIS)[number] | (typeof SITES_ALEX)[number]
export type MemoryRegion = (typeof REGIONS)[number]
export type MemoryChapter = { id: number; region: number; phase: number; year: number; month: number; day: number; sites: MemoryPlace[]; witnesses: MemoryWitness[] }
export type MemoryPlace = { id: number; chapter: number; region: number; phase: number; slot: number; title: string; site: MemorySite }
export type MemoryWitness = { id: number; name: string; role: string; intro: string; line: string; correctSlot: number; needs: number[]; friend: boolean }

export const MEMORY_CHAPTERS: MemoryChapter[] = REGIONS.flatMap((region, area) =>
  PHASES.map((_phase, phase) => {
    const id = area * PHASES.length + phase
    const pool = area < 20 ? SITES_ABIS : SITES_ALEX
    const sites = pool.slice(phase * 5, phase * 5 + 5).map((site, slot): MemoryPlace => ({
      id: id * 5 + slot,
      chapter: id,
      region: area,
      phase,
      slot,
      title: `${site[0]} · ${region[0]}`,
      site,
    }))
    const witnesses = WITNESS_ROLES[phase].map((role, seat): MemoryWitness => {
      const fr = FRIENDS[area]
      const friend = fr && fr.phase === phase && fr.seat === seat ? fr : undefined
      const globalWitnessIdx = id * 2 + seat // 0..399
      const genName = `${FIRST_NAMES[globalWitnessIdx % FIRST_NAMES.length]} ${FAMILY_NAMES[Math.floor(globalWitnessIdx / FIRST_NAMES.length)]}`
      const correctSlot = seat === 0 ? area % 2 : 2 + ((area + phase) % 3)
      return {
        id: globalWitnessIdx,
        name: friend?.name ?? genName,
        role,
        friend: Boolean(friend),
        correctSlot,
        needs: seat === 0 ? [0, 1] : [2, 3, 4],
        intro: friend?.intro ?? `${role} في ${region[3]}. محتفظ بعلامة «${region[5]}» لصالح ${region[4]}.`,
        line: `${friend?.line ?? `أنا ${role} بنفسي؛ علامة «${region[5]}» هي اللي حسمت الفرق قدامي.`} دليل «${sites[correctSlot].site[2]}» بيطابق سنة ${YEARS[phase]}.`,
      }
    })
    // Unique valid date across all 40 areas in each era (months 1..10, days 3/9/15/21)
    const month = 1 + Math.floor(area / 4)
    const day = 3 + (area % 4) * 6
    return { id, region: area, phase, year: YEARS[phase], month, day, sites, witnesses }
  }))

export const MEMORY_PLACES = MEMORY_CHAPTERS.flatMap(chapter => chapter.sites)
export const MEMORY_PEOPLE = MEMORY_CHAPTERS.flatMap(chapter => chapter.witnesses.map(witness => ({ chapter, witness })))

export function relatedChapters(chapter: MemoryChapter): MemoryChapter[] {
  const sameArea = MEMORY_CHAPTERS[chapter.region * PHASES.length + (chapter.phase + 1) % PHASES.length]
  const corroboratingArea = MEMORY_CHAPTERS[((chapter.region + (chapter.phase + 1) * 3) % REGIONS.length) * PHASES.length + chapter.phase]
  const partnerArea = MEMORY_CHAPTERS[((chapter.region + REGIONS.length - 1) % REGIONS.length) * PHASES.length + chapter.phase]
  const [first, second] = MAIN_REGIONS[chapter.phase]
  const nextLead = chapter.region === first
    ? MEMORY_CHAPTERS[second * PHASES.length + chapter.phase]
    : chapter.region === second && chapter.phase + 1 < PHASES.length
      ? MEMORY_CHAPTERS[MAIN_REGIONS[chapter.phase + 1][0] * PHASES.length + chapter.phase + 1]
      : undefined
  return [...new Set([nextLead, sameArea, corroboratingArea, partnerArea].filter((c): c is MemoryChapter => Boolean(c)))]
}
